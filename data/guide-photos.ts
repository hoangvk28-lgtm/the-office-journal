/** Slug pattern -> photo set(s), first match wins. Extra sets only fill gaps. */
const RULES: { test: RegExp; sets: string[] }[] = [
  { test: /studio-monitor|standing-desk-converter/, sets: [] },
  { test: /pen-holder|pencil-holder|pen-cup/, sets: ["pen-holder", "desk-organizer"] },
  { test: /desk-mat|desk-pad|mouse-pad/, sets: ["desk-mat"] },
  { test: /monitor-stand|monitor-riser/, sets: ["monitor-stand"] },
  { test: /laptop-stand|laptop-riser/, sets: ["laptop-stand"] },
  { test: /desk-shel|desk-hutch|over-desk-shel/, sets: ["desk-shelf"] },
  { test: /drawer-organi/, sets: ["drawer-organizer", "desk-organizer"] },
  { test: /desk-organi|desktop-organi/, sets: ["desk-organizer"] },
];

function hash(s: string) { let h = 0; for (const c of s) h = (h * 31 + c.charCodeAt(0)) >>> 0; return h; }

/** Up to `max` photos for a guide, rotated per slug so siblings differ. */
export function getGuidePhotos(slug: string, max = 3): GuidePhoto[] {
  const rule = RULES.find((r) => r.test.test(slug));
  if (!rule) return [];
  const out: GuidePhoto[] = [];
  for (const set of rule.sets) {
    const list = guidePhotoSets[set] ?? [];
    const off = hash(slug + set) % (list.length || 1);
    for (let i = 0; i < list.length && out.length < max; i++) {
      const p = list[(off + i) % list.length];
      if (!out.some((o) => o.src === p.src)) out.push(p);
    }
    if (out.length >= max) break;
  }
  return out;
}
